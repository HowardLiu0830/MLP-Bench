"""The nine failure modes of the FL verification error-type checklist (Appendix F.3)."""
from __future__ import annotations

__all__ = ["ERROR_TAXONOMY"]


ERROR_TAXONOMY = (
    "\n\n# Error-type checklist\n"
    "Judge for yourself whether each theorem's proof is correct — do NOT assume "
    "any particular one is flawed, and do NOT assume any error exists at all. Test "
    "every step of every theorem against EACH failure mode below; report the EARLIEST "
    "step within whichever theorem contains a genuine error (if any theorem does). "
    "For the structural types (assumption / "
    "quantifier / circularity), the error lives at the step that first ASSUMES or "
    "asserts the bad thing, NOT the later step where it visibly breaks — always "
    "trace any defect back to its origin.\n"
    "1. invalid_inequality_or_equation — an asserted (in)equality or identity is false "
    "as written. Check its direction, constants, and whether it holds for ALL values in "
    "range, not just the typical case.\n"
    "2. incorrect_computation — an algebraic/arithmetic manipulation (expansion, "
    "derivative, integral, sum, simplification) is wrong. Re-derive the line independently.\n"
    "3. boundary_or_degenerate_case_omission — the argument silently assumes an "
    "interior/non-degenerate case and fails at an endpoint, zero, empty set, tie, or "
    "equality boundary that the setting permits. BEFORE flagging: check whether the "
    "omitted case is VACUOUS or TRIVIALLY TRUE in the stated regime (the claimed bound "
    "already holds there for free, or the statement's own hypotheses exclude it). If so, "
    "the proof is correct-as-written — do not flag it.\n"
    "4. unstated_assumption_or_regularity_gap — a step relies on a property the theorem "
    "does NOT guarantee (measurability, separability, continuity, integrability, "
    "finiteness). Flag the step that FIRST relies on it. BEFORE flagging: ask whether the "
    "STANDARD ONE-LINE REPAIR restores the step with the SAME constants and the same "
    "order — an epsilon-approximate maximizer plus continuity in place of an unattained "
    "sup/inf, a limiting argument over compact exhaustions, a separability or "
    "measurability convention. If such a repair exists, the proof is correct-as-written — "
    "do NOT flag it. Regularity conventions routine in this literature (i.i.d. sampling, "
    "bounded loss, measurability of a sup over a separable or countable class, the stated "
    "step-size regime) are GRANTED, not missing.\n"
    "5. logical_gap_missing_case — an inference covers only some of the cases/objects it "
    "claims to; a case the conclusion actually requires is never handled.\n"
    "6. wrong_quantifier_or_scope — an ∃ / for-fixed / high-probability object is later "
    "used as if it held ∀ / uniformly / simultaneously (e.g. a per-θ event treated as a "
    "uniform event, or inf/sup interchanged with another quantifier). Flag the step that "
    "FIRST makes the illegal quantifier move.\n"
    "7. wrong_or_misapplied_named_result — a named theorem/inequality is cited but its "
    "hypotheses are not met here, or it is invoked in a stronger form than it provides.\n"
    "8. circular_or_assumes_conclusion — a step assumes (often in disguise) the very "
    "claim being proved, or asserts as given a bound that should be derived/inducted. "
    "Flag the EARLIEST step that smuggles the conclusion in, NOT the downstream step "
    "where it is used.\n"
    "9. unjustified_or_hand_wavy_step — a real logical leap is waved through as "
    "'standard'/'clearly' with no valid justification and no true citable result behind it. "
    "'Standard'/'clearly' phrasing is NOT itself an error: flag only if you can name the "
    "standard result the author would be appealing to AND show it does not actually apply "
    "here. If you cannot name it, you have not found an error.\n"
)
